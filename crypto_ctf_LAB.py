"""Fixed XOR"""

def fixed_xor(hex1, hex2):
    # Decode hexadecimal strings into bytes
    bytes1 = bytes.fromhex(hex1)
    bytes2 = bytes.fromhex(hex2)

    # Check whether both buffers have equal length
    if len(bytes1) != len(bytes2):
        raise ValueError("Both buffers must have equal length")

    # XOR corresponding bytes and convert the result to hex
    result = bytes(a ^ b for a, b in zip(bytes1, bytes2))

    return result.hex()


