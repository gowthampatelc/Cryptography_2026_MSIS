# --------------------------------------------------
# 4. Estimate key size using normalized distances
# --------------------------------------------------
def rank_key_sizes(ciphertext, min_size=2, max_size=40):
    results = []

    for key_size in range(min_size, max_size + 1):
        # Use the first 8 complete blocks
        blocks = [
            ciphertext[i:i + key_size]
            for i in range(0, key_size * 8, key_size)
        ]

        if len(blocks) < 4 or any(
            len(block) != key_size for block in blocks
        ):
            continue

        distances = []

        # Average all pairwise normalized distances
        for i in range(len(blocks)):
            for j in range(i + 1, len(blocks)):
                distance = hamming_distance(blocks[i], blocks[j])
                distances.append(distance / key_size)

        results.append((sum(distances) / len(distances), key_size))

    return sorted(results)


# --------------------------------------------------
# 5. Break repeating-key XOR for a given key size
# --------------------------------------------------
def break_repeating_key_xor(ciphertext, key_size):
    key = bytearray()

    # Transpose blocks: group bytes encrypted with the same key byte
    for position in range(key_size):
        block = ciphertext[position::key_size]
        _, key_byte, _ = crack_single_byte_xor(block)
        key.append(key_byte)

    key = bytes(key)

    plaintext = bytes(
        byte ^ key[i % len(key)]
        for i, byte in enumerate(ciphertext)
    )

    return key, plaintext


