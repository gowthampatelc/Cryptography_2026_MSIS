import urllib.request
from collections import Counter

URL = "https://cryptopals.com/static/challenge-data/8.txt"
BLOCK_SIZE = 16


def detect_ecb(hex_string, block_size=16):
    ciphertext = bytes.fromhex(hex_string.strip())

    # Split ciphertext into fixed-size blocks
    blocks = [
        ciphertext[i:i + block_size]
        for i in range(0, len(ciphertext), block_size)
    ]

    # Ignore incomplete final blocks
    complete_blocks = [
        block for block in blocks
        if len(block) == block_size
    ]

    counts = Counter(complete_blocks)

    # Count repeated blocks beyond their first occurrence
    repeated_count = sum(
        count - 1 for count in counts.values()
        if count > 1
    )

    return repeated_count, len(counts)


